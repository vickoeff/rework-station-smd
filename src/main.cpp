// ================= Buzzer =================
struct BuzzStep
{
  uint16_t freq;
  uint16_t duration;
};

const BuzzStep PATTERN_STARTUP[] = {{1000, 100}, {0, 40}, {1500, 100}, {0, 40}, {2200, 150}};
const BuzzStep PATTERN_BUTTON[] = {{2500, 30}};
const BuzzStep PATTERN_RUN[] = {{1800, 100}};
const BuzzStep PATTERN_OFF[] = {{900, 80}, {0, 60}, {600, 120}};
const BuzzStep PATTERN_ERROR[] = {{400, 150}, {0, 100}};

const BuzzStep *buzzerPattern = nullptr;
uint8_t buzzerPatternLen = 0;
uint8_t buzzerStep = 0;
unsigned long buzzerStepStart = 0;
bool buzzerPlaying = false;

unsigned long lastErrorBeepTime = 0;
const unsigned long errorBeepInterval = 1500; // ms

void playPattern(const BuzzStep *pattern, uint8_t len)
{
  buzzerPattern = pattern;
  buzzerPatternLen = len;
  buzzerStep = 0;
  buzzerStepStart = millis();
  buzzerPlaying = true;
  if (pattern[0].freq > 0)
    tone(PIN_BUZZER, pattern[0].freq);
  else
    noTone(PIN_BUZZER);
}

void updateBuzzer()
{
  if (!buzzerPlaying)
    return;
  unsigned long now = millis();
  if (now - buzzerStepStart >= buzzerPattern[buzzerStep].duration)
  {
    buzzerStep++;
    buzzerStepStart = now;
    if (buzzerStep >= buzzerPatternLen)
    {
      buzzerPlaying = false;
      noTone(PIN_BUZZER);
      return;
    }
    if (buzzerPattern[buzzerStep].freq > 0)
    {
      tone(PIN_BUZZER, buzzerPattern[buzzerStep].freq);
    }
    else
    {
      noTone(PIN_BUZZER);
    }
  }
}

