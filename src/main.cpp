void drawUI()
{
  static unsigned long lastDraw = 0;
  if (millis() - lastDraw < 150)
    return;
  lastDraw = millis();

  u8g2.firstPage();
  do
  {
    u8g2.setFontMode(1);
    u8g2.setBitmapMode(1);
    if (currentState == STATE_ERROR)
    {
      drawErrorScreen();
    }
    else
    {
      drawMainScreen();
    }
  } while (u8g2.nextPage());
}

