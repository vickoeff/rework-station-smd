// ================= Setup =================
void setup()
{
  Serial.begin(9600);

  pinMode(PIN_BTN_UP, INPUT_PULLUP);
  pinMode(PIN_BTN_DOWN, INPUT_PULLUP);
  pinMode(PIN_BTN_SELECT, INPUT_PULLUP);
  pinMode(PIN_HANDLE_SW, INPUT_PULLUP);
  pinMode(PIN_SSR, OUTPUT);
  setSSR(false);
  pinMode(PIN_BUZZER, OUTPUT);
  digitalWrite(PIN_BUZZER, LOW);

  EEPROM.get(EEPROM_ADDR_SETPOINT, setpoint);
  if (isnan(setpoint) || setpoint < TEMP_MIN_SET || setpoint > TEMP_MAX_SET)
  {
    setpoint = TEMP_DEFAULT;
  }

  u8g2.begin();
  windowStartTime = millis();

  playPattern(PATTERN_STARTUP, sizeof(PATTERN_STARTUP) / sizeof(PATTERN_STARTUP[0]));
}

// ================= Main Loop =================
void loop()
{
  readHandleSwitch();
  readTemperature();
  handleButtons();
  updateBuzzer();
  debugPrintSerial();

  if (thermoFault || input >= TEMP_MAX_SAFETY)
  {
    currentState = STATE_ERROR;
  }
  else if (handleInStand)
  {
    currentState = STATE_STANDBY;
  }
  else
  {
    currentState = STATE_RUN;
  }

  if (currentState != lastState)
  {
    if (currentState == STATE_RUN)
    {
      playPattern(PATTERN_RUN, sizeof(PATTERN_RUN) / sizeof(PATTERN_RUN[0]));
      effectiveSetpointInitialized = false;
    }
    else if (currentState == STATE_STANDBY)
    {
      playPattern(PATTERN_OFF, sizeof(PATTERN_OFF) / sizeof(PATTERN_OFF[0]));
    }
    else if (currentState == STATE_ERROR)
    {
      playPattern(PATTERN_ERROR, sizeof(PATTERN_ERROR) / sizeof(PATTERN_ERROR[0]));
      lastErrorBeepTime = millis();
    }
    lastState = currentState;
  }

  if (currentState == STATE_ERROR && !buzzerPlaying && (millis() - lastErrorBeepTime >= errorBeepInterval))
  {
    playPattern(PATTERN_ERROR, sizeof(PATTERN_ERROR) / sizeof(PATTERN_ERROR[0]));
    lastErrorBeepTime = millis();
  }

  switch (currentState)
  {
  case STATE_RUN:
    computePID();
    applySSR();
    break;
  case STATE_STANDBY:
    output = 0;
    integral = 0;
    setSSR(false);
    break;
  case STATE_ERROR:
    output = 0;
    integral = 0;
    setSSR(false);
    break;
  }

  drawUI();
}

// ================= Sensor & Kontrol =================
unsigned long lastTempReadTime = 0;
const unsigned long tempReadInterval = 250; // ms

void readTemperature()
{
  unsigned long now = millis();
  if (now - lastTempReadTime < tempReadInterval)
    return;
  lastTempReadTime = now;

  double raw = thermocouple.readCelsius();
  if (isnan(raw))
  {
    thermoFault = true;
  }
  else
  {
    thermoFault = false;
    input = raw;
  }
}

void debugPrintSerial()
{
  static unsigned long lastPrint = 0;
  unsigned long now = millis();
  if (now - lastPrint < 500)
    return;
  lastPrint = now;

  Serial.print(F("Input(C): "));
  Serial.print(input);
  Serial.print(F("  TargetAsli: "));
  Serial.print(setpoint);
  Serial.print(F("  TargetRamp: "));
  Serial.print(effectiveSetpoint);
  Serial.print(F("  Output(%): "));
  Serial.print(output);
  Serial.print(F("  ThermoFault: "));
  Serial.println(thermoFault ? "YA" : "tidak");
}

const double MAX_OUTPUT_STEP = 5.0;
void computePID()
{
  unsigned long now = millis();
  if (now - lastPidTime < pidInterval)
    return;
  double dt = (now - lastPidTime) / 1000.0;
  lastPidTime = now;

  if (!effectiveSetpointInitialized)
  {
    effectiveSetpoint = input;
    effectiveSetpointInitialized = true;
  }

  double maxSetpointStep = SETPOINT_RAMP_RATE * dt;
  if (setpoint > effectiveSetpoint)
  {
    effectiveSetpoint = min(effectiveSetpoint + maxSetpointStep, setpoint);
  }
  else if (setpoint < effectiveSetpoint)
  {
    effectiveSetpoint = max(effectiveSetpoint - maxSetpointStep, setpoint);
  }

  double error = effectiveSetpoint - input;

  double tentativeIntegral = integral + error * dt;
  double tentativeOutput = Kp * error + Ki * tentativeIntegral + Kd * (error - lastError) / dt;

  double targetOutput;
  if (tentativeOutput > 100)
  {
    targetOutput = 100;
  }
  else if (tentativeOutput < 0)
  {
    targetOutput = 0;
  }
  else
  {
    integral = tentativeIntegral;
    targetOutput = tentativeOutput;
  }

  // Ramp limiter
  if (targetOutput > output)
  {
    output = min(output + MAX_OUTPUT_STEP, targetOutput);
  }
  else if (targetOutput < output)
  {
    output = max(output - MAX_OUTPUT_STEP, targetOutput);
  }

  lastError = error;
}

void applySSR()
{
  unsigned long now = millis();
  if (now - windowStartTime > windowSize)
  {
    windowStartTime += windowSize;
  }
  unsigned long onTime = (unsigned long)((output / 100.0) * windowSize);
  if ((now - windowStartTime) < onTime)
  {
    setSSR(true);
  }
  else
  {
    setSSR(false);
  }
}

void handleButtons()
{
  if (millis() - lastBtnTime < debounceDelay)
    return;

  if (digitalRead(PIN_BTN_UP) == LOW)
  {
    setpoint += 5;
    if (setpoint > TEMP_MAX_SET)
      setpoint = TEMP_MAX_SET;
    EEPROM.put(EEPROM_ADDR_SETPOINT, setpoint);
    playPattern(PATTERN_BUTTON, sizeof(PATTERN_BUTTON) / sizeof(PATTERN_BUTTON[0]));
    lastBtnTime = millis();
  }
  else if (digitalRead(PIN_BTN_DOWN) == LOW)
  {
    setpoint -= 5;
    if (setpoint < TEMP_MIN_SET)
      setpoint = TEMP_MIN_SET;
    EEPROM.put(EEPROM_ADDR_SETPOINT, setpoint);
    playPattern(PATTERN_BUTTON, sizeof(PATTERN_BUTTON) / sizeof(PATTERN_BUTTON[0]));
    lastBtnTime = millis();
  }
  else if (digitalRead(PIN_BTN_SELECT) == LOW)
  {
    playPattern(PATTERN_BUTTON, sizeof(PATTERN_BUTTON) / sizeof(PATTERN_BUTTON[0]));
    lastBtnTime = millis();
  }
}

